/**
 * Minimal gettext-style translation for the plugin UI (settings screen and menu labels).
 *
 * The Joplin plugin API does not provide a translation mechanism, so the plugin ships its own:
 *   - Strings are marked in the source code as _('English text'). The English text is the msgid.
 *   - Translators edit src/locales/<locale>.po (e.g. ja_JP.po) with Poedit or any gettext tool.
 *   - At build time, scripts/i18n.js compiles all .po files into src/locales/translations.json,
 *     which is bundled into the plugin. The .po files themselves are not read at run time.
 *   - At start-up, index.ts calls setLocale() with Joplin's UI language.
 * See "Translations" in README.md for the workflow.
 */

/** Translations of one locale: msgid (English) -> msgstr (translated text). */
export type Catalog = Record<string, string>;

/** Translations of all locales, keyed by locale code such as "ja_JP". */
export type Catalogs = Record<string, Catalog>;

// Generated by `npm run i18n:compile` (also run by `npm run dist` and `npm test`); not committed.
// require() is used instead of import so that no TypeScript JSON module setting is needed.
// eslint-disable-next-line @typescript-eslint/no-var-requires
const bundledCatalogs: Catalogs = require('./locales/translations.json');

/** Catalog of the current locale. Empty means "no translation": msgids are shown as they are. */
let currentCatalog: Catalog = {};

/**
 * Finds the catalog that best matches a Joplin locale code.
 *
 * Lookup order, e.g. for "ja_JP":
 *   1. exact match              "ja_JP"
 *   2. language only            "ja"
 *   3. same language, any region "ja_XX" (first one in alphabetical order)
 * Returns null if nothing matches; the UI is then shown in English.
 *
 * @param locale   Joplin locale code ("ja_JP", "en_GB", ...). "-" is accepted as a separator too.
 * @param catalogs Catalogs to search. Defaults to the ones bundled with the plugin (parameter for tests).
 */
export function findCatalog(locale: string | null | undefined, catalogs: Catalogs = bundledCatalogs): Catalog | null {
	if (!locale) return null;
	const normalized = locale.replace('-', '_');
	if (catalogs[normalized]) return catalogs[normalized];

	const language = normalized.split('_')[0];
	if (catalogs[language]) return catalogs[language];

	const sameLanguage = Object.keys(catalogs).sort().find(key => key.split('_')[0] === language);
	return sameLanguage ? catalogs[sameLanguage] : null;
}

/**
 * Selects the language used by _().
 * Call it once at start-up, before registering settings and menus, because Joplin keeps the labels
 * that were passed at registration time. (Changing Joplin's language requires a restart anyway.)
 */
export function setLocale(locale: string | null | undefined, catalogs: Catalogs = bundledCatalogs): void {
	currentCatalog = findCatalog(locale, catalogs) || {};
}

/**
 * Returns the translation of a UI string, or the string itself when there is no translation.
 *
 * The argument must be a string literal, because scripts/i18n.js extracts the strings to translate
 * from the source code with xgettext (keyword "_"). A variable or an expression would not be found.
 *
 * @example
 * label: _('Format Table'),
 */
export function _(msgid: string): string {
	const translated = currentCatalog[msgid];
	return translated ? translated : msgid;
}
